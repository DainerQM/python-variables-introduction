"""Simple examples of Python variables.

Run this file with:
    python variables_examples.py
"""

print("PYTHON VARIABLES")
print("----------------")

print("\n1. CREATE VARIABLES")
name = "Ana"
age = 20
is_learning = True
print("Name:", name)
print("Age:", age)
print("Is learning:", is_learning)

print("\n2. CHANGE A VARIABLE")
score = 10
print("First score:", score)
score = 15
print("New score:", score)

print("\n3. USE A VARIABLE IN A CALCULATION")
apples = 3
more_apples = 2
total_apples = apples + more_apples
print("Apples:", apples)
print("More apples:", more_apples)
print("Total apples:", total_apples)

print("\n4. USE THE CURRENT VALUE")
coins = 5
print("Starting coins:", coins)
coins = coins + 1
print("Coins after adding one:", coins)

print("\n5. DIFFERENT KINDS OF VALUES")
city = "London"
temperature = 18.5
is_sunny = False
print("City:", city)
print("Temperature:", temperature)
print("Is sunny:", is_sunny)

print("\n6. TWO NAMES, TWO VALUES")
first_score = 10
second_score = first_score
first_score = 20
print("First score:", first_score)
print("Second score:", second_score)

print("\nEnd of examples.")
